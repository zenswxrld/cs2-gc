"""Read-only: derive GC message IDs from the protobuf descriptors embedded in a CS2 client.dll.

Scans the file as data (nothing is loaded or executed) for serialized FileDescriptorProto
blobs, decodes only their enums, and writes a C++ header. Uses Python 3.9+ standard library.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import sys

# Enums the GC bridge dispatches on. A missing one means the build differs; fail loudly.
WANTED = (
    "EGCBaseClientMsg",
    "EGCBaseMsg",
    "ESOMsg",
    "EGCItemMsg",
    "ECsgoGCMsg",
    "EGCMsgResponse",
    "GCConnectionStatus",
)
# Enums whose values are message types on the GC wire; only these feed MessageName().
WIRE_ENUMS = ("EGCBaseClientMsg", "EGCBaseMsg", "ESOMsg", "EGCItemMsg", "ECsgoGCMsg")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
NAME_PREFIX = re.compile(rb"\x0a([\x05-\x7f])([A-Za-z0-9_/.]{4,120}\.proto)")
MAX_FIELD = 2_000_000


def read_varint(data, pos):
    result = shift = 0
    while True:
        if pos >= len(data) or shift > 63:
            raise ValueError("bad varint")
        byte = data[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        shift += 7
        if not byte & 0x80:
            return result, pos


def read_fields(data, pos=0, end=None):
    """Decode (field, wire type, value) triples until the data stops looking like protobuf."""
    end = len(data) if end is None else end
    fields = []
    while pos < end:
        try:
            tag, nxt = read_varint(data, pos)
            number, wire = tag >> 3, tag & 7
            if number == 0 or wire not in (0, 1, 2, 5):
                break
            if wire == 0:
                value, nxt = read_varint(data, nxt)
            elif wire == 1:
                value, nxt = data[nxt:nxt + 8], nxt + 8
            elif wire == 5:
                value, nxt = data[nxt:nxt + 4], nxt + 4
            else:
                length, nxt = read_varint(data, nxt)
                if length > MAX_FIELD or nxt + length > end:
                    break
                value, nxt = data[nxt:nxt + length], nxt + length
        except ValueError:
            break
        fields.append((number, wire, value))
        pos = nxt
    return fields


def decode_enum(raw):
    name, values = None, []
    for number, wire, value in read_fields(raw):
        if number == 1 and wire == 2:
            name = value.decode("utf-8", "replace")
        elif number == 2 and wire == 2:
            inner = {n: v for n, _, v in read_fields(value)}
            label, num = inner.get(1), inner.get(2, 0)
            if isinstance(label, bytes) and isinstance(num, int):
                # int32 enum numbers are stored as sign-extended 64-bit varints
                values.append((label.decode("utf-8", "replace"), num - (1 << 64) if num >= 1 << 63 else num))
    return name, values


def embedded_enums(data):
    """Map enum name to (proto file, values) for every descriptor blob found in data."""
    found = {}
    for match in NAME_PREFIX.finditer(data):
        if match.group(1)[0] != len(match.group(2)):
            continue
        filename = match.group(2).decode()
        pos = match.start()
        while True:  # top-level FileDescriptorProto fields, field 5 is enum_type
            try:
                tag, nxt = read_varint(data, pos)
            except ValueError:
                break
            number, wire = tag >> 3, tag & 7
            if not 1 <= number <= 12 or wire not in (0, 2):
                break
            if wire == 0:
                _, pos = read_varint(data, nxt)
                continue
            try:
                length, nxt = read_varint(data, nxt)
            except ValueError:
                break
            if length > MAX_FIELD or nxt + length > len(data):
                break
            if number == 5:
                name, values = decode_enum(data[nxt:nxt + length])
                if name and values:
                    found.setdefault(name, (filename, values))
            pos = nxt + length
    return found


def pe_timestamp(data):
    if data[:2] != b"MZ" or len(data) < 64:
        raise ValueError("Not a PE executable")
    offset = struct.unpack_from("<I", data, 0x3C)[0]
    if offset + 12 > len(data) or data[offset:offset + 4] != b"PE\0\0":
        raise ValueError("Invalid PE header")
    machine, = struct.unpack_from("<H", data, offset + 4)
    if machine != 0x8664:
        raise ValueError("Not an x64 module")
    return struct.unpack_from("<I", data, offset + 8)[0]


def render_header(data, enums, build_id=None):
    timestamp = pe_timestamp(data)
    lines = [
        "// Generated by tools/extract_gc_protocol.py. Do not edit.",
        "// Message IDs come from protobuf descriptors embedded in the client below;",
        "// they are not validated against any other build.",
        f"// client.dll sha256: {hashlib.sha256(data).hexdigest()}",
        f"// client.dll coff timestamp: {timestamp}",
    ]
    if build_id:
        lines.append(f"// steam build id (supplied by the user): {build_id}")
    lines += ["#pragma once", "", "#include <cstdint>", "", "namespace cs2_gc::gc_msg", "{"]
    for name in WANTED:
        filename, values = enums[name]
        lines.append(f"// {filename}")
        lines.append(f"namespace {name}")
        lines.append("{")
        seen = set()
        for label, number in values:
            if not IDENTIFIER.match(label) or label in seen:
                raise ValueError(f"Unusable enumerator name in {name}: {label!r}")
            seen.add(label)
            if not 0 <= number <= 0xFFFFFFFF:
                raise ValueError(f"{name}.{label} does not fit in uint32")
            lines.append(f"inline constexpr std::uint32_t {label} = {number};")
        lines += ["}", ""]
    lines += ["struct NameEntry", "{", "    std::uint32_t id;", "    const char *name;", "};",
              "inline constexpr NameEntry kMessageNames[] = {"]
    for name in WIRE_ENUMS:
        for label, number in enums[name][1]:
            lines.append(f'    {{{number}, "{name}::{label}"}},')
    lines += ["};", "",
              "// First match wins; nullptr for IDs this build's descriptors do not name.",
              "inline const char *MessageName(std::uint32_t id)", "{",
              "    for (const NameEntry &entry : kMessageNames)", "        if (entry.id == id)",
              "            return entry.name;", "    return nullptr;", "}", "}"]
    return "\n".join(lines) + "\n"


def generate(client_dll, build_id=None):
    data = Path(client_dll).read_bytes()
    enums = embedded_enums(data)
    missing = [name for name in WANTED if name not in enums]
    if missing:
        raise ValueError("Descriptors not found in this client.dll: " + ", ".join(missing))
    return render_header(data, enums, build_id)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("client_dll", type=Path, help="Path to CS2's game/csgo/bin/win64/client.dll")
    parser.add_argument("--out", type=Path, required=True,
                        help="C++ header to create; an existing file is never overwritten")
    parser.add_argument("--build-id", help="Steam build ID to record in the header comment")
    args = parser.parse_args(argv)
    try:
        if args.build_id is not None and not args.build_id.isdigit():
            raise ValueError("--build-id must be digits only")
        text = generate(args.client_dll, args.build_id)
        with args.out.open("x", encoding="utf-8", newline="\n") as destination:
            destination.write(text)
        print(f"Wrote {args.out}. IDs are derived from this client only; runtime behavior is unverified.")
        return 0
    except (OSError, ValueError, struct.error) as error:
        print(f"Extraction failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
