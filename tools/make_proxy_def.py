"""Read-only: write a module-definition file that forwards a Steam API DLL's exports to a renamed copy.

Used to build a stand-in steam_api64.dll that passes every call through to the real library
(renamed steam_api64_real.dll) except the functions the stand-in implements itself.
Uses Python 3.9+ standard library.
"""
import argparse
from pathlib import Path
import re
import struct
import sys

# Implemented by cs2_gc/proxy/steam_api_proxy.cpp, so they must not be forwarded.
OVERRIDDEN = (
    "SteamInternal_FindOrCreateUserInterface",
    "SteamInternal_CreateInterface",
    "SteamAPI_RegisterCallback",
    "SteamAPI_UnregisterCallback",
    "SteamAPI_RunCallbacks",
    "SteamGameServer_RunCallbacks",
    "SteamInternal_FindOrCreateGameServerInterface",
)
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_@?$]*$")


def export_names(data, proxy_target=None):
    """Names of every named export, read from the PE export directory without loading the file."""
    if data[:2] != b"MZ" or len(data) < 0x40:
        raise ValueError("Not a PE executable")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if pe + 24 > len(data) or data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("Invalid PE header")
    machine, sections = struct.unpack_from("<HH", data, pe + 4)
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    optional = pe + 24
    magic = struct.unpack_from("<H", data, optional)[0]
    if machine != 0x8664 or magic != 0x20B:
        raise ValueError("Not an x64 module")
    directory = optional + 112
    if directory + 8 > len(data):
        raise ValueError("Truncated optional header")
    export_rva, export_size = struct.unpack_from("<II", data, directory)
    if not export_rva:
        raise ValueError("Module has no exports")

    table = optional + optional_size
    spans = []
    for index in range(sections):
        base = table + index * 40
        if base + 40 > len(data):
            raise ValueError("Truncated section table")
        _, virtual_size, virtual_address, raw_size, raw_pointer = struct.unpack_from("<8sIIII", data, base)
        spans.append((virtual_address, max(virtual_size, raw_size), raw_pointer, raw_size))

    def offset(rva, length=1):
        for virtual_address, size, raw_pointer, raw_size in spans:
            if virtual_address <= rva and rva + length <= virtual_address + size:
                result = rva - virtual_address + raw_pointer
                if result + length <= len(data):
                    return result
        raise ValueError("Export table points outside the file")

    base = offset(export_rva, 40)
    function_count, name_count = struct.unpack_from("<II", data, base + 20)
    names_rva = struct.unpack_from("<I", data, base + 32)[0]
    functions_rva = struct.unpack_from("<I", data, base + 28)[0]
    ordinals_rva = struct.unpack_from("<I", data, base + 36)[0]
    if name_count > 100000 or function_count > 100000:
        raise ValueError("Implausible export count")
    if name_count != function_count:
        raise ValueError("Exports without names cannot be forwarded safely")

    names = []
    for index in range(name_count):
        name_rva = struct.unpack_from("<I", data, offset(names_rva + 4 * index, 4))[0]
        start = offset(name_rva)
        end = data.find(b"\0", start, start + 512)
        if end < 0:
            raise ValueError("Unterminated export name")
        name = data[start:end].decode("ascii")
        if not IDENTIFIER.match(name):
            raise ValueError(f"Unusable export name: {name!r}")
        ordinal = struct.unpack_from("<H", data, offset(ordinals_rva + 2 * index, 2))[0]
        function_rva = struct.unpack_from("<I", data, offset(functions_rva + 4 * ordinal, 4))[0]
        if export_rva <= function_rva < export_rva + export_size:
            if not proxy_target:
                raise ValueError(f"{name} is itself a forwarder; refusing to chain it")
            start = offset(function_rva)
            end = data.find(b"\0", start, start + 512)
            expected = f"{proxy_target}.{name}".encode('ascii')
            if end < 0 or data[start:end] != expected:
                raise ValueError(f"{name} forwards somewhere other than {proxy_target}.{name}")
        names.append(name)
    if len(set(names)) != len(names):
        raise ValueError("Duplicate export names")
    return names


def render(names, target):
    if not re.fullmatch(r"[A-Za-z0-9_]+", target):
        raise ValueError("Target module name must be letters, digits and underscores")
    lines = ["; Generated by tools/make_proxy_def.py. Do not edit.", "EXPORTS"]
    for name in names:
        lines.append(f"    {name}" if name in OVERRIDDEN else f"    {name} = {target}.{name}")
    missing = [name for name in OVERRIDDEN if name not in names]
    if missing:
        raise ValueError("The DLL does not export: " + ", ".join(missing))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("steam_api_dll", type=Path, help="Path to the game's original steam_api64.dll")
    parser.add_argument("--out", type=Path, required=True, help=".def file to create; never overwritten")
    parser.add_argument("--target", default="steam_api64_real",
                        help="Module name the exports forward to (without .dll)")
    parser.add_argument("--from-proxy", action="store_true",
                        help="Read an existing proxy; validate each forwarder and still target the original module directly")
    args = parser.parse_args(argv)
    try:
        text = render(export_names(args.steam_api_dll.read_bytes(), args.target if args.from_proxy else None), args.target)
        with args.out.open("x", encoding="ascii", newline="\n") as destination:
            destination.write(text)
        print(f"Wrote {args.out} ({text.count(chr(10)) - 2} exports).")
        return 0
    except (OSError, ValueError, struct.error) as error:
        print(f"Failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
